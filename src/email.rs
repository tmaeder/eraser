/// ponytail: a network error or timeout after DATA can mean the server accepted the mail, so
/// a retry may duplicate it; a duplicate deletion request beats a lost one.
const SMTP_RETRY: crate::retry::Policy = crate::retry::Policy::new(3, Duration::from_secs(1));
/// Per SMTP command; 3 tries + backoff stay under the callers' 90 s send timeout.
const SMTP_TIMEOUT: Duration = Duration::from_secs(25);

/// Sanitized SMTP failure; `transient` = worth retrying.
#[derive(Debug)]
struct SmtpFailure {
    message: String,
    transient: bool,
}

impl SmtpFailure {
    fn permanent(message: String) -> Self {
        SmtpFailure {
            message,
            transient: false,
        }
    }
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Message {
    pub to: String,
    pub from: String,
    pub subject: String,
    pub body: String,
}

/// Outcome of one send.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct SendResult {
    pub success: bool,
    pub message_id: String,
    pub error: Option<String>,
}

impl SendResult {
    fn failed(err: impl std::fmt::Display) -> Self {
        Self {
            success: false,
            message_id: String::new(),
            error: Some(err.to_string()),
        }
    }
}

/// Public origin of the web UI (`serve --public-origin`); enables the open-tracking pixel.
static PUBLIC_ORIGIN: RwLock<Option<String>> = RwLock::new(None);

/// Set once at startup by `serve`; senders created afterwards embed the tracking pixel.
pub fn set_public_origin(origin: Option<String>) {
    *PUBLIC_ORIGIN
        .write()
        .unwrap_or_else(std::sync::PoisonError::into_inner) =
        origin.map(|o| o.trim_end_matches('/').to_string());
}

fn public_origin() -> Option<String> {
    PUBLIC_ORIGIN
        .read()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
        .clone()
}

/// 128-bit random, base64url (22 chars): Message-ID local part and pixel token in one.
fn new_token() -> String {
    use base64::Engine;
    let mut bytes = [0u8; 16];
    rand::fill(&mut bytes[..]);
    base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(bytes)
}

/// The pixel token of a Message-ID generated by [`SmtpSender`] (`<token@domain>`), else None.
pub fn tracking_token(message_id: &str) -> Option<&str> {
    let (token, _) = message_id.strip_prefix('<')?.split_once('@')?;
    (token.len() == 22
        && token
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_'))
    .then_some(token)
}

fn html_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// The HTML twin of a plain-text body: escaped, line breaks kept, plus the 1x1 pixel.
fn html_body(text: &str, origin: &str, token: &str) -> String {
    format!(
        "<!DOCTYPE html>\n<html><body><pre style=\"white-space:pre-wrap;font-family:inherit\">{}</pre>\n<img src=\"{origin}/p/{token}.gif\" width=\"1\" height=\"1\" alt=\"\"></body></html>\n",
        html_escape(text)
    )
}

/// Builds the RFC 5322 message. Returns (message, Message-ID).
///
/// With `tracking`: own Message-ID `<token@sender-domain>`, read-receipt headers and, with a
/// public origin, multipart/alternative (unchanged text + HTML with the pixel). Without it: the
/// pre-tracking format, plain text only and no Message-ID (the server adds one); the returned
/// ID is then empty.
fn build_email(
    msg: &Message,
    token: &str,
    public_origin: Option<&str>,
    tracking: bool,
) -> Result<(lettre::Message, String)> {
    let from: Mailbox = msg.from.parse()?;
    let to: Mailbox = msg.to.parse()?;
    let builder = lettre::Message::builder()
        .from(from.clone())
        .to(to)
        .subject(msg.subject.clone());
    if !tracking {
        let email = builder
            .header(ContentType::TEXT_PLAIN)
            .body(msg.body.clone())?;
        return Ok((email, String::new()));
    }
    let message_id = format!("<{token}@{}>", from.email.domain());
    let receipt_to = from.email.to_string();
    let builder = builder
        .message_id(Some(message_id.clone()))
        .raw_header(HeaderValue::new(
            HeaderName::new_from_ascii_str("Disposition-Notification-To"),
            receipt_to.clone(),
        ))
        .raw_header(HeaderValue::new(
            HeaderName::new_from_ascii_str("Return-Receipt-To"),
            receipt_to,
        ));
    let email = match public_origin {
        Some(origin) => builder.multipart(MultiPart::alternative_plain_html(
            msg.body.clone(),
            html_body(&msg.body, origin, token),
        ))?,
        None => builder
            .header(ContentType::TEXT_PLAIN)
            .body(msg.body.clone())?,
    };
    Ok((email, message_id))
}

pub trait Sender: Send + Sync {
    /// `sequence` only feeds the untracked SMTP result ID (`smtp-<to>-<sequence>`).
    fn send<'a>(&'a self, msg: &'a Message, sequence: Option<usize>) -> BoxFuture<'a, SendResult>;
    fn name(&self) -> &'static str;
}

/// Sending pace for a provider. Bursts get accounts blocked: iCloud locked an account after 81
/// mails in four minutes (SMTP "550 5.1.1 Mailbox does not exist", IMAP AUTHENTICATIONFAILED).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Pacing {
    /// Between two consecutive sends, across all send paths.
    pub min_interval: Duration,
    /// Attempts (any outcome) in any 60 minutes; `i64::MAX` = no cap.
    pub per_hour: i64,
    pub per_day: i64,
}

/// Provider presets (account.provider). `rate_limit_ms` (options) sets the custom interval and
/// can only slow a known provider down, never speed it up.
pub fn pacing(provider: &str, rate_limit_ms: i64) -> Pacing {
    let configured = Duration::from_millis(u64::try_from(rate_limit_ms).unwrap_or(0));
    let (secs, per_hour, per_day) = match provider {
        "icloud" => (45, 25, 100),
        "gmail" => (20, 60, 400),
        "outlook" => (30, 30, 250),
        _ => {
            let interval = if rate_limit_ms > 0 {
                configured
            } else {
                Duration::from_millis(2000)
            };
            return Pacing {
                min_interval: interval,
                per_hour: i64::MAX,
                per_day: 250,
            };
        }
    };
    Pacing {
        min_interval: Duration::from_secs(secs).max(configured),
        per_hour,
        per_day,
    }
}

/// Display name of a provider for limit messages.
pub fn provider_name(provider: &str) -> &str {
    match provider {
        "icloud" => "iCloud",
        "gmail" => "Gmail",
        "outlook" => "Outlook",
        _ => "your provider",
    }
}

pub fn is_apple_address(addr: &str) -> bool {
    let a = addr.trim().to_lowercase();
    ["@icloud.com", "@me.com", "@mac.com"]
        .iter()
        .any(|d| a.ends_with(d))
}

/// Whether a send/login error means the provider rejected our account (not one recipient):
/// SMTP 530/534/535 and other auth failures, IMAP AUTHENTICATIONFAILED, and for iCloud any
/// 550 5.1.1. iCloud's submission server does not verify outside recipients while sending, so
/// "Mailbox does not exist" there refers to the sender's own (blocked) mailbox.
pub fn is_account_rejection(cfg: &crate::config::Config, err: &str) -> bool {
    let e = err.to_lowercase();
    let apple = cfg.account.provider == "icloud"
        || is_apple_address(&cfg.email.smtp.username)
        || is_apple_address(&cfg.email.from);
    e.contains("auth") || (apple && e.contains("5.1.1"))
}

/// Why sending must not happen now.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Hold {
    /// Circuit breaker tripped (reason).
    Blocked(String),
    /// Hourly cap full until this time.
    Hourly {
        until: chrono::DateTime<chrono::Local>,
        per_hour: i64,
        provider: String,
    },
    Daily(i64),
    Error(String),
}

impl std::fmt::Display for Hold {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Hold::Blocked(reason) => write!(
                f,
                "Sending is paused: your mail provider rejected Eraser's login ({reason}). Create a new app-specific password under Settings → Account and click Test connection."
            ),
            Hold::Hourly {
                until,
                per_hour,
                provider,
            } => write!(
                f,
                "Hourly limit reached ({per_hour}/h for {}) — try again at {}",
                provider_name(provider),
                until.format("%H:%M")
            ),
            Hold::Daily(n) => write!(f, "Daily limit of {n} emails reached"),
            Hold::Error(e) => write!(f, "not sent: {e}"),
        }
    }
}

/// Sends allowed right now: Ok(wait before sending) or the reason to hold.
pub fn check_turn(
    store: &crate::history::Store,
    cfg: &crate::config::Config,
) -> Result<Duration, Hold> {
    let err = |e: anyhow::Error| Hold::Error(format!("{e:#}"));
    if let Some((_, reason)) = store.account_blocked().map_err(err)? {
        return Err(Hold::Blocked(reason));
    }
    let p = cfg.pacing();
    let now = chrono::Local::now();
    let midnight = now
        .date_naive()
        .and_hms_opt(0, 0, 0)
        .and_then(|m| m.and_local_timezone(chrono::Local).earliest())
        .unwrap_or(now);
    if store.emails_sent_since(midnight).map_err(err)? >= p.per_day {
        return Err(Hold::Daily(p.per_day));
    }
    let hour = chrono::TimeDelta::hours(1);
    let times = store.send_times_since(now - hour).map_err(err)?;
    let n = times.len() as i64;
    if n >= p.per_hour {
        // Free again once the oldest attempts beyond the cap leave the 60-minute window.
        let until = times[(n - p.per_hour) as usize] + hour;
        return Err(Hold::Hourly {
            until,
            per_hour: p.per_hour,
            provider: cfg.account.provider.clone(),
        });
    }
    let since_last = times
        .last()
        .and_then(|t| (now - *t).to_std().ok())
        .unwrap_or(p.min_interval);
    Ok(p.min_interval.saturating_sub(since_last))
}

/// Waits out the minimum interval since the last send; Err = must not send now.
pub async fn wait_turn(
    store: &crate::history::Store,
    cfg: &crate::config::Config,
) -> Result<(), Hold> {
    let wait = check_turn(store, cfg)?;
    if !wait.is_zero() {
        tokio::time::sleep(wait).await;
    }
    Ok(())
}

/// Trips the circuit breaker when `err` is an account-level rejection: records the block (all
/// send paths refuse until a successful connection test). True = stop sending now.
pub fn trip_on_rejection(
    store: &crate::history::Store,
    cfg: &crate::config::Config,
    err: &str,
) -> bool {
    if !is_account_rejection(cfg, err) {
        return false;
    }
    tracing::warn!("mail provider rejected the account ({err}); sending paused");
    if let Err(e) = store.block_account(err) {
        tracing::error!("failed to record account block: {e:#}");
    }
    true
}

pub fn new_sender(cfg: &EmailConfig) -> Result<Box<dyn Sender>> {
    if cfg.provider.is_empty() || cfg.provider == "smtp" {
        let mut sender = SmtpSender::new(cfg.smtp.clone());
        sender.tracking = cfg.tracking;
        return Ok(Box::new(sender));
    }
    bail!(
        "unknown email provider: {} (only smtp is supported)",
        cfg.provider
    )
}

/// Rejects header-injection characters and anything that is not an RFC 5322 address.
pub fn validate_email(email: &str) -> Result<()> {
    if email.contains(['\r', '\n', ',', ';']) {
        bail!("email contains invalid characters");
    }
    email
        .parse::<Mailbox>()
        .map_err(|e| anyhow!("invalid email format: {e}"))?;
    Ok(())
}

fn validate_message(msg: &Message) -> Result<()> {
    validate_email(&msg.from).map_err(|e| anyhow!("invalid sender: {e}"))?;
    validate_email(&msg.to).map_err(|e| anyhow!("invalid recipient: {e}"))?;
    Ok(())
}

pub struct SmtpSender {
    config: SmtpConfig,
    /// Embeds the open-tracking pixel when set (see [`set_public_origin`]) and `tracking` is on.
    public_origin: Option<String>,
    /// `email.tracking`: own Message-ID, read-receipt headers, pixel. Off = pre-tracking format.
    tracking: bool,
}

impl SmtpSender {
    pub fn new(config: SmtpConfig) -> Self {
        Self {
            config,
            public_origin: public_origin(),
            tracking: false,
        }
    }

    async fn send_inner(&self, msg: &Message, sequence: Option<usize>) -> SendResult {
        if let Err(e) = validate_message(msg) {
            return SendResult::failed(e);
        }
        // Reject headers with CRLF to prevent injection
        if msg.subject.contains(['\r', '\n']) {
            return SendResult::failed("subject contains invalid characters");
        }
        if !self.config.use_tls && !self.config.username.is_empty() {
            return SendResult::failed("SMTP auth requires TLS");
        }

        // One Message-ID for all retries, so a duplicate delivery is recognizable as such.
        let (email, message_id) = match build_email(
            msg,
            &new_token(),
            self.public_origin.as_deref(),
            self.tracking,
        ) {
            Ok(built) => built,
            Err(e) => return SendResult::failed(format!("could not build email: {e}")),
        };
        let delivered = crate::retry::run(
            SMTP_RETRY,
            || self.deliver(&email),
            |f: &SmtpFailure| {
                if f.transient {
                    crate::retry::Verdict::Retry
                } else {
                    crate::retry::Verdict::Stop
                }
            },
        )
        .await;
        if let Err(f) = delivered {
            return SendResult::failed(f.message);
        }
        let message_id = if message_id.is_empty() {
            // Pre-tracking ID (Go formats a missing value with %d as "%!d(<nil>)").
            let seq = sequence.map_or_else(|| "%!d(<nil>)".to_string(), |s| s.to_string());
            format!("smtp-{}-{seq}", msg.to)
        } else {
            message_id
        };

        SendResult {
            success: true,
            message_id,
            error: None,
        }
    }

    fn transport(&self) -> std::result::Result<AsyncSmtpTransport<Tokio1Executor>, SmtpFailure> {
        let generic = || SmtpFailure::permanent("SMTP error: check your configuration".into());

        let host = self.config.host.as_str();
        let port = u16::try_from(self.config.port).map_err(|_| generic())?;

        Ok(if self.config.use_tls {
            let builder = if port == 587 {
                // Port 587 (iCloud, Outlook) uses STARTTLS instead of implicit TLS
                AsyncSmtpTransport::<Tokio1Executor>::starttls_relay(host)
            } else {
                AsyncSmtpTransport::<Tokio1Executor>::relay(host)
            }
            .map_err(|e| SmtpFailure::permanent(sanitize_smtp_error(&e)))?;
            builder
                .port(port)
                .timeout(Some(SMTP_TIMEOUT))
                .credentials(Credentials::new(
                    self.config.username.clone(),
                    self.config.password.clone(),
                ))
                .authentication(vec![Mechanism::Plain])
                .build()
        } else {
            // No auth: STARTTLS if the server offers it.
            let tls = TlsParameters::new(host.to_string())
                .map_err(|e| SmtpFailure::permanent(sanitize_smtp_error(&e)))?;
            AsyncSmtpTransport::<Tokio1Executor>::builder_dangerous(host)
                .port(port)
                .timeout(Some(SMTP_TIMEOUT))
                .tls(Tls::Opportunistic(tls))
                .build()
        })
    }

    /// One delivery attempt; the error message is already sanitized.
    async fn deliver(&self, email: &lettre::Message) -> std::result::Result<(), SmtpFailure> {
        self.transport()?
            .send(email.clone())
            .await
            .map(|_| ())
            .map_err(|e| {
                let message = sanitize_smtp_error(&e);
                SmtpFailure {
                    transient: is_transient(&e) && message != AUTH_FAILED,
                    message,
                }
            })
    }

    /// Connects and logs in (no mail sent). Err: the sanitized server reply.
    pub async fn test_connection(&self) -> std::result::Result<(), String> {
        if !self.config.use_tls && !self.config.username.is_empty() {
            return Err("SMTP auth requires TLS".into());
        }
        let transport = self.transport().map_err(|f| f.message)?;
        match tokio::time::timeout(TEST_TIMEOUT, transport.test_connection()).await {
            Err(_) => Err("SMTP server did not respond in time".into()),
            Ok(Err(e)) => Err(sanitize_smtp_error(&e)),
            Ok(Ok(true)) => Ok(()),
            Ok(Ok(false)) => Err("SMTP server closed the connection".into()),
        }
    }
}

/// Upper bound for a connection test (connect, TLS, login).
pub const TEST_TIMEOUT: Duration = Duration::from_secs(20);

impl Sender for SmtpSender {
    fn send<'a>(&'a self, msg: &'a Message, sequence: Option<usize>) -> BoxFuture<'a, SendResult> {
        Box::pin(self.send_inner(msg, sequence))
    }

    fn name(&self) -> &'static str {
        "smtp"
    }
}

const AUTH_FAILED: &str = "SMTP authentication failed";

/// 4xx replies, timeouts and connection/network errors; never 5xx, TLS or client errors.
fn is_transient(err: &lettre::transport::smtp::Error) -> bool {
    err.is_transient()
        || err.is_timeout()
        || !(err.is_permanent()
            || err.is_tls()
            || err.is_client()
            || err.is_response()
            || err.is_transport_shutdown())
}

/// Maps transport errors to messages that never leak server responses or credentials.
fn sanitize_smtp_error(err: &lettre::transport::smtp::Error) -> String {
    // lettre does not tag auth-stage failures, so treat 53x replies (auth required /
    // rejected) as auth failures too.
    let auth_code = err
        .status()
        .is_some_and(|c| c.to_string().starts_with("53"));
    sanitize_message(&err.to_string(), auth_code)
}

fn sanitize_message(text: &str, auth_code: bool) -> String {
    let s = text.to_lowercase();
    if auth_code || s.contains("auth") {
        AUTH_FAILED.into()
    } else if s.contains("certificate") {
        "TLS certificate error".into()
    } else {
        // Server replies carry no credentials; show them so rejections are diagnosable.
        let detail: String = text.split_whitespace().collect::<Vec<_>>().join(" ");
        let detail: String = detail.chars().take(200).collect();
        match detail
            .strip_prefix("permanent error (")
            .and_then(|r| r.split_once("): "))
        {
            Some((code, reply)) => format!("Rejected by mail server: {code} {reply}"),
            None => format!("SMTP error: {detail}"),
        }
    }
}

