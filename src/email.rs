use std::time::Duration;

/// ponytail: a network error or timeout after DATA can mean the server accepted the mail, so
/// a retry may duplicate it; a duplicate deletion request beats a lost one.
const SMTP_RETRY: crate::retry::Policy = crate::retry::Policy::new(3, Duration::from_secs(1));
/// Per SMTP command; 3 tries + backoff stay under the callers' 90 s send timeout.
const SMTP_TIMEOUT: Duration = Duration::from_secs(25);

/// Sanitized SMTP failure; `transient` = worth retrying.
#[derive(Debug)]
struct SmtpFailure {
    message: String,
    transient: bool,
}

impl SmtpFailure {
    fn permanent(message: String) -> Self {
        SmtpFailure {
            message,
            transient: false,
        }
    }
}

#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Message {
    pub to: String,
    pub from: String,
    pub subject: String,
    pub body: String,
}

/// Outcome of one send.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct SendResult {
    pub success: bool,
    pub message_id: String,
    pub error: Option<String>,
}

impl SendResult {
    fn failed(err: impl std::fmt::Display) -> Self {
        Self {
            success: false,
            message_id: String::new(),
            error: Some(err.to_string()),
        }
    }
}

/// Public origin of the web UI (`serve --public-origin`); enables the open-tracking pixel.
static PUBLIC_ORIGIN: RwLock<Option<String>> = RwLock::new(None);

/// Set once at startup by `serve`; senders created afterwards embed the tracking pixel.
pub fn set_public_origin(origin: Option<String>) {
    *PUBLIC_ORIGIN
        .write()
        .unwrap_or_else(std::sync::PoisonError::into_inner) =
        origin.map(|o| o.trim_end_matches('/').to_string());
}

fn public_origin() -> Option<String> {
    PUBLIC_ORIGIN
        .read()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
        .clone()
}

/// 128-bit random, base64url (22 chars): Message-ID local part and pixel token in one.
fn new_token() -> String {
    use base64::Engine;
    let mut bytes = [0u8; 16];
    rand::fill(&mut bytes[..]);
    base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(bytes)
}

/// The pixel token of a Message-ID generated by [`SmtpSender`] (`<token@domain>`), else None.
pub fn tracking_token(message_id: &str) -> Option<&str> {
    let (token, _) = message_id.strip_prefix('<')?.split_once('@')?;
    (token.len() == 22
        && token
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_'))
    .then_some(token)
}

fn html_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// The HTML twin of a plain-text body: escaped, line breaks kept, plus the 1x1 pixel.
fn html_body(text: &str, origin: &str, token: &str) -> String {
    format!(
        "<!DOCTYPE html>\n<html><body><pre style=\"white-space:pre-wrap;font-family:inherit\">{}</pre>\n<img src=\"{origin}/p/{token}.gif\" width=\"1\" height=\"1\" alt=\"\"></body></html>\n",
        html_escape(text)
    )
}

/// Builds the RFC 5322 message: own Message-ID `<token@sender-domain>`, read-receipt headers
/// and, with a public origin, multipart/alternative (unchanged text + HTML with the pixel).
/// Returns (message, Message-ID).
fn build_email(
    msg: &Message,
    token: &str,
    public_origin: Option<&str>,
) -> Result<(lettre::Message, String)> {
    let from: Mailbox = msg.from.parse()?;
    let to: Mailbox = msg.to.parse()?;
    let message_id = format!("<{token}@{}>", from.email.domain());
    let receipt_to = from.email.to_string();
    let builder = lettre::Message::builder()
        .from(from)
        .to(to)
        .subject(msg.subject.clone())
        .message_id(Some(message_id.clone()))
        .raw_header(HeaderValue::new(
            HeaderName::new_from_ascii_str("Disposition-Notification-To"),
            receipt_to.clone(),
        ))
        .raw_header(HeaderValue::new(
            HeaderName::new_from_ascii_str("Return-Receipt-To"),
            receipt_to,
        ));
    let email = match public_origin {
        Some(origin) => builder.multipart(MultiPart::alternative_plain_html(
            msg.body.clone(),
            html_body(&msg.body, origin, token),
        ))?,
        None => builder
            .header(ContentType::TEXT_PLAIN)
            .body(msg.body.clone())?,
    };
    Ok((email, message_id))
}

pub trait Sender: Send + Sync {
    /// `sequence` is unused by the SMTP sender (it generates its own Message-ID).
    fn send<'a>(&'a self, msg: &'a Message, sequence: Option<usize>) -> BoxFuture<'a, SendResult>;
    fn name(&self) -> &'static str;
}

/// Emails per day per provider (iCloud allows ~1000/day, Gmail ~500/day; stay well under both).
pub fn daily_limit(provider: &str) -> i64 {
    match provider {
        "sendgrid" | "resend" => 500,
        _ => 250,
    }
}

pub fn new_sender(cfg: &EmailConfig) -> Result<Box<dyn Sender>> {
    if cfg.provider.is_empty() || cfg.provider == "smtp" {
        return Ok(Box::new(SmtpSender::new(cfg.smtp.clone())));
    }
    bail!(
        "unknown email provider: {} (only smtp is supported)",
        cfg.provider
    )
}

/// Rejects header-injection characters and anything that is not an RFC 5322 address.
pub fn validate_email(email: &str) -> Result<()> {
    if email.contains(['\r', '\n', ',', ';']) {
        bail!("email contains invalid characters");
    }
    email
        .parse::<Mailbox>()
        .map_err(|e| anyhow!("invalid email format: {e}"))?;
    Ok(())
}

fn validate_message(msg: &Message) -> Result<()> {
    validate_email(&msg.from).map_err(|e| anyhow!("invalid sender: {e}"))?;
    validate_email(&msg.to).map_err(|e| anyhow!("invalid recipient: {e}"))?;
    Ok(())
}

pub struct SmtpSender {
    config: SmtpConfig,
    /// Embeds the open-tracking pixel when set (see [`set_public_origin`]).
    public_origin: Option<String>,
}

impl SmtpSender {
    pub fn new(config: SmtpConfig) -> Self {
        Self {
            config,
            public_origin: public_origin(),
        }
    }

    async fn send_inner(&self, msg: &Message) -> SendResult {
        if let Err(e) = validate_message(msg) {
            return SendResult::failed(e);
        }
        // Reject headers with CRLF to prevent injection
        if msg.subject.contains(['\r', '\n']) {
            return SendResult::failed("subject contains invalid characters");
        }
        if !self.config.use_tls && !self.config.username.is_empty() {
            return SendResult::failed("SMTP auth requires TLS");
        }

        // One Message-ID for all retries, so a duplicate delivery is recognizable as such.
        let Ok((email, message_id)) = build_email(msg, &new_token(), self.public_origin.as_deref())
        else {
            return SendResult::failed("SMTP error: check your configuration");
        };
        let delivered = crate::retry::run(
            SMTP_RETRY,
            || self.deliver(&email),
            |f: &SmtpFailure| {
                if f.transient {
                    crate::retry::Verdict::Retry
                } else {
                    crate::retry::Verdict::Stop
                }
            },
        )
        .await;
        if let Err(f) = delivered {
            return SendResult::failed(f.message);
        }

        SendResult {
            success: true,
            message_id,
            error: None,
        }
    }

    /// One delivery attempt; the error message is already sanitized.
    async fn deliver(&self, email: &lettre::Message) -> std::result::Result<(), SmtpFailure> {
        let generic = || SmtpFailure::permanent("SMTP error: check your configuration".into());

        let host = self.config.host.as_str();
        let port = u16::try_from(self.config.port).map_err(|_| generic())?;

        let transport = if self.config.use_tls {
            let builder = if port == 587 {
                // Port 587 (iCloud, Outlook) uses STARTTLS instead of implicit TLS
                AsyncSmtpTransport::<Tokio1Executor>::starttls_relay(host)
            } else {
                AsyncSmtpTransport::<Tokio1Executor>::relay(host)
            }
            .map_err(|e| SmtpFailure::permanent(sanitize_smtp_error(&e)))?;
            builder
                .port(port)
                .timeout(Some(SMTP_TIMEOUT))
                .credentials(Credentials::new(
                    self.config.username.clone(),
                    self.config.password.clone(),
                ))
                .authentication(vec![Mechanism::Plain])
                .build()
        } else {
            // No auth: STARTTLS if the server offers it.
            let tls = TlsParameters::new(host.to_string())
                .map_err(|e| SmtpFailure::permanent(sanitize_smtp_error(&e)))?;
            AsyncSmtpTransport::<Tokio1Executor>::builder_dangerous(host)
                .port(port)
                .timeout(Some(SMTP_TIMEOUT))
                .tls(Tls::Opportunistic(tls))
                .build()
        };

        transport
            .send(email.clone())
            .await
            .map(|_| ())
            .map_err(|e| {
                let message = sanitize_smtp_error(&e);
                SmtpFailure {
                    transient: is_transient(&e) && message != AUTH_FAILED,
                    message,
                }
            })
    }
}

impl Sender for SmtpSender {
    fn send<'a>(&'a self, msg: &'a Message, _sequence: Option<usize>) -> BoxFuture<'a, SendResult> {
        Box::pin(self.send_inner(msg))
    }

    fn name(&self) -> &'static str {
        "smtp"
    }
}

const AUTH_FAILED: &str = "SMTP authentication failed";

/// 4xx replies, timeouts and connection/network errors; never 5xx, TLS or client errors.
fn is_transient(err: &lettre::transport::smtp::Error) -> bool {
    err.is_transient()
        || err.is_timeout()
        || !(err.is_permanent()
            || err.is_tls()
            || err.is_client()
            || err.is_response()
            || err.is_transport_shutdown())
}

/// Maps transport errors to messages that never leak server responses or credentials.
fn sanitize_smtp_error(err: &lettre::transport::smtp::Error) -> String {
    // lettre does not tag auth-stage failures, so treat 53x replies (auth required /
    // rejected) as auth failures too.
    let auth_code = err
        .status()
        .is_some_and(|c| c.to_string().starts_with("53"));
    sanitize_message(&err.to_string(), auth_code)
}

fn sanitize_message(text: &str, auth_code: bool) -> String {
    let s = text.to_lowercase();
    if auth_code || s.contains("auth") {
        AUTH_FAILED.into()
    } else if s.contains("certificate") {
        "TLS certificate error".into()
    } else {
        "SMTP error: check your configuration".into()
    }
}

