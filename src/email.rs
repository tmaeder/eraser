    /// Minimal fake SMTP server (no TLS, no auth). `mail_from[i]` is the reply to MAIL FROM on
    /// connection `i` (later connections reuse the last one). Returns (port, DATA of the
    /// connections that got that far, number of connections).
    async fn fake_smtp(
        mail_from: Vec<&'static str>,
    ) -> (u16, tokio::task::JoinHandle<(String, usize)>) {
        let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
        let port = listener.local_addr().unwrap().port();
        let server = tokio::spawn(async move {
            let mut data = String::new();
            for conn in 0.. {
                let accepted =
                    tokio::time::timeout(Duration::from_secs(3), listener.accept()).await;
                let Ok(Ok((sock, _))) = accepted else {
                    return (data, conn);
                };
                let mail_reply = mail_from[conn.min(mail_from.len() - 1)];
                let (r, mut w) = sock.into_split();
                let mut lines = BufReader::new(r).lines();
                w.write_all(b"220 fake ESMTP\r\n").await.unwrap();
                let mut in_data = false;
                while let Ok(Some(line)) = lines.next_line().await {
                    if in_data {
                        if line == "." {
                            in_data = false;
                            w.write_all(b"250 queued\r\n").await.unwrap();
                        } else {
                            data.push_str(&line);
                            data.push('\n');
                        }
                        continue;
                    }
                    let reply = match line.get(..4).unwrap_or("").to_uppercase().as_str() {
                        "EHLO" => "250 fake".to_string(),
                        "MAIL" => mail_reply.to_string(),
                        "DATA" => {
                            in_data = true;
                            "354 go".into()
                        }
                        "QUIT" => {
                            let _ = w.write_all(b"221 bye\r\n").await;
                            break;
                        }
                        _ => "250 ok".into(),
                    };
                    if w.write_all(format!("{reply}\r\n").as_bytes())
                        .await
                        .is_err()
                    {
                        break;
                    }
                }
                if data.contains("Subject:") {
                    return (data, conn + 1);
                }
            }
            unreachable!()
        });
        (port, server)
    }

    #[tokio::test]
    async fn sends_plain_text_message() {
        let (port, server) = fake_smtp(vec!["250 ok"]).await;
        let r = smtp(i64::from(port), false, "").send(&msg(), Some(7)).await;
        assert!(r.success, "{:?}", r.error);
        assert!(tracking_token(&r.message_id).is_some(), "own Message-ID");
        assert!(r.message_id.ends_with("@example.com>"));
        let (data, conns) = server.await.unwrap();
        assert_eq!(conns, 1);
        assert!(data.contains("From: me@example.com\n"), "{data}");
        assert!(data.contains("To: privacy@broker.com\n"));
        assert!(data.contains("Subject: Personal Data Removal Request\n"));
        assert!(data.contains(&format!("Message-ID: {}\n", r.message_id)));
        assert!(data.contains("Disposition-Notification-To: me@example.com\n"));
        assert!(data.contains("Content-Type: text/plain; charset=utf-8\n"));
    }

    #[tokio::test]
    async fn sends_pixel_with_public_origin() {
        let (port, server) = fake_smtp(vec!["250 ok"]).await;
        let mut s = smtp(i64::from(port), false, "");
        s.public_origin = Some("https://erase.example".into());
        let r = s.send(&msg(), None).await;
        assert!(r.success, "{:?}", r.error);
        let token = tracking_token(&r.message_id).unwrap();
        let (data, _) = server.await.unwrap();
        assert!(data.contains("multipart/alternative"), "{data}");
        assert!(data.contains(&format!("https://erase.example/p/{token}.gif")));
    }

    fn formatted(origin: Option<&str>) -> String {
        let mut m = msg();
        m.body = "Line <1> & \"two\"\nLine 2".into();
        let (email, id) = build_email(&m, "AAAAAAAAAAAAAAAAAAAAAA", origin).unwrap();
        assert_eq!(id, "<AAAAAAAAAAAAAAAAAAAAAA@example.com>");
        String::from_utf8(email.formatted()).unwrap()
    }

    #[test]
    fn plain_text_and_receipt_headers_without_origin() {
        let raw = formatted(None);
        assert!(
            raw.contains("Message-ID: <AAAAAAAAAAAAAAAAAAAAAA@example.com>\r\n"),
            "{raw}"
        );
        assert!(raw.contains("Disposition-Notification-To: me@example.com\r\n"));
        assert!(raw.contains("Return-Receipt-To: me@example.com\r\n"));
        assert!(raw.contains("Content-Type: text/plain; charset=utf-8\r\n"));
        assert!(!raw.contains("multipart") && !raw.contains("<img"));
    }

    #[test]
    fn multipart_with_pixel_with_origin() {
        let raw = formatted(Some("https://erase.example"));
        assert!(
            raw.contains("Disposition-Notification-To: me@example.com\r\n"),
            "{raw}"
        );
        assert!(raw.contains("Return-Receipt-To: me@example.com\r\n"));
        assert!(raw.contains("Content-Type: multipart/alternative;"));
        assert!(raw.contains("Content-Type: text/plain; charset=utf-8"));
        assert!(raw.contains("Content-Type: text/html; charset=utf-8"));
        let parsed = mail_parser::MessageParser::default()
            .parse(raw.as_bytes())
            .unwrap();
        assert_eq!(
            parsed.body_text(0).unwrap().replace("\r\n", "\n"),
            "Line <1> & \"two\"\nLine 2"
        );
        let html = parsed.body_html(0).unwrap().replace("\r\n", "\n");
        assert!(
            html.contains("Line &lt;1&gt; &amp; &quot;two&quot;\nLine 2"),
            "{html}"
        );
        assert!(html.contains(
            r#"<img src="https://erase.example/p/AAAAAAAAAAAAAAAAAAAAAA.gif" width="1" height="1" alt="">"#
        ));
        assert!(!html.contains("<link") && !html.contains("<style"));
    }

